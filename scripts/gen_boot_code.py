#!/usr/bin/env python3
"""Generate rehome/patch/bootcode.py from Rehome's boot code sources (needs nasm).

Rehome writes its own boot code into the VM's copy of a disk whose boot code is
missing (see rehome/patch/legacy.py). The sources are rehome/patch/*.asm; the
assembled bytes are kept in a Python module so running Rehome needs no
assembler.

    scripts/gen_boot_code.py > rehome/patch/bootcode.py
"""

import subprocess
import sys
import tempfile
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "rehome" / "patch"
# name: (source, nasm options, size)
CODE = {
    "MBR": ("mbr.asm", [], 440),
    "WIN9X_FAT16": ("win9x_boot.asm", [], 512),
    "WIN9X_FAT32": ("win9x_boot.asm", ["-D", "FAT32"], 512),
}


def assemble(source: str, options: list[str]) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "out.bin"
        subprocess.run(["nasm", "-f", "bin", *options, "-o", str(out), str(SRC / source)],
                       check=True)
        return out.read_bytes()


def main() -> None:
    print('"""Rehome\'s boot code, assembled from rehome/patch/mbr.asm and win9x_boot.asm.\n\n'
          'Generated by scripts/gen_boot_code.py; do not edit by hand.\n"""\n')
    for name, (source, options, size) in CODE.items():
        code = assemble(source, options)
        if len(code) != size:
            sys.exit(f"{source} {' '.join(options)}: {len(code)} bytes, expected {size}")
        hexed = code.hex()
        lines = [hexed[i:i + 96] for i in range(0, len(hexed), 96)]
        print(f"{name} = bytes.fromhex(")
        for line in lines:
            print(f'    "{line}"')
        print(")\n")


if __name__ == "__main__":
    main()
